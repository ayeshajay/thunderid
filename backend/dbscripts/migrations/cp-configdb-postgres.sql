CREATE INDEX IF NOT EXISTS idx_secret_deployment ON "SECRET" (DEPLOYMENT_ID);

CREATE TABLE IF NOT EXISTS "TENANT" (
    DEPLOYMENT_ID VARCHAR(255) NOT NULL,
