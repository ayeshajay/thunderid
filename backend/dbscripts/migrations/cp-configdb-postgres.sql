-- ThunderID schema update: control plane configdb (PostgreSQL)
--
-- Brings an existing database up to this release. No table is dropped and no row is touched: new
-- tables are created, and existing tables keep their data while their keys are widened in place.
--
-- The only change to a table that already exists is its constraints. Replacing a primary key means
-- dropping the old constraint and adding the new one; the table and its rows stay where they are.
--
--   old   PRIMARY KEY (ID)
--   new   PRIMARY KEY (DEPLOYMENT_ID, ID)
--
-- That is what lets one database hold more than one deployment: the same id may exist in two of them
-- without colliding. Foreign keys pointing at those tables are widened to match.
--
-- Safe to run again: constraint drops are conditional and every CREATE is IF NOT EXISTS.

BEGIN;

-- ------------------------------------------------------------------ new tables
CREATE TABLE IF NOT EXISTS "DATA_PLANE_JOB" (
    DEPLOYMENT_ID VARCHAR(255) NOT NULL,
    ID            VARCHAR(64)  NOT NULL,
    -- The deployment this is for, as "<org>:<env>". DEPLOYMENT_ID above is the organization, so that
    -- an organization's queue sits in one partition with its gateways.
    DATA_PLANE_ID VARCHAR(255) NOT NULL,
    GATEWAY_ID        VARCHAR(64),
    -- What to do: "import" applies configuration, "secret_put" stores one credential.
    TYPE          VARCHAR(32)  NOT NULL,
    -- The request, as JSON. Encrypted when it carries a credential, which is what ENCRYPTED records:
    -- a secret is held here only until it is delivered, and never in the clear.
    PAYLOAD       TEXT         NOT NULL,
    ENCRYPTED     CHAR(1)      DEFAULT '0' NOT NULL,
    -- pending -> claimed -> done | failed.
    STATUS        VARCHAR(16)  NOT NULL,
    -- Which pod is delivering it, for diagnosing a job stuck in claimed.
    CLAIMED_BY    VARCHAR(255),
    -- What the Data Plane answered, as JSON, or why it could not be delivered.
    RESULT        TEXT,
    ERROR         TEXT,
    ATTEMPTS      INTEGER      DEFAULT 0 NOT NULL,
    CREATED_AT    TIMESTAMPTZ  DEFAULT NOW(),
    UPDATED_AT    TIMESTAMPTZ  DEFAULT NOW(),
    COMPLETED_AT  TIMESTAMPTZ,
    PRIMARY KEY (DEPLOYMENT_ID, ID)
);
CREATE INDEX IF NOT EXISTS idx_data_plane_job_queue ON "DATA_PLANE_JOB" (DATA_PLANE_ID, STATUS, CREATED_AT);

CREATE TABLE IF NOT EXISTS "DATA_PLANE_TOKEN" (
